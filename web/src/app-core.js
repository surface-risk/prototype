function go() {
  const name = (location.hash || "#home").slice(1) || "home";
  const r = ROUTES[name] || ROUTES.home;
  const key = ROUTES[name] ? name : "home";
  $$("[data-nav]").forEach((a) => {
    const n = a.dataset.nav;
    const on = n === key || (n === "demo" && ["setup", "survey"].includes(key));
    if (on) a.setAttribute("aria-current", "page"); else a.removeAttribute("aria-current");
  });
  // Fresh <main> per view so listeners from the previous view are dropped.
  const old = $("#main"), main = old.cloneNode(false);
  old.replaceWith(main);
  main.innerHTML = r.render();
  if (r.after) r.after(main);
  window.scrollTo(0, 0);
}

