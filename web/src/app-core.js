const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const f1 = (n) => (n == null || Number.isNaN(n) ? "–" : (Math.round(n * 10) / 10).toFixed(1));
const f0 = (n) => (n == null || Number.isNaN(n) ? "–" : String(Math.round(n)));
const sign = (n) => (n > 0 ? "+" : n < 0 ? "−" : "±") + Math.abs(Math.round(n * 10) / 10).toFixed(1);
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));

const BANDS = U.bands; // [{label, from}]
function bandOf(score) {
  let idx = 0;
  BANDS.forEach((b, i) => { if (score >= b.from) idx = i; });
  return { idx, label: BANDS[idx].label };
}
const P = U.parameters;
function zone(v) { return v < P.archetype_low ? "Low" : v < P.archetype_high ? "Mid" : "High"; }
function archetypeOf(loss, perf) {
  const key = zone(loss) + "|" + zone(perf);
  return U.archetypes.find((a) => a.key === key) || { name: "–", description: "" };
}
