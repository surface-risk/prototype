// Staff vs management view per area (dumbbell), sorted by gap.
function gapChart({ rows = R.areas, compact = false } = {}) {
  const data = [...rows].sort((a, b) => b.gap - a.gap);
  const fs = compact ? 12 : 11.5, rowH = compact ? 21 : 22, top = 30, W = compact ? 480 : 660;
  const left = compact ? 196 : 238, right = 96;
  const maxCh = compact ? 26 : 34;
  const H = top + data.length * rowH + 30;
  const x = (v) => left + (v / 100) * (W - left - right);
  const nm = (s) => (s.length > maxCh ? s.slice(0, maxCh - 1) + "…" : s);
  let s = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Staff and management scores by area for the fictional sample firm" style="font-size:${fs}px">`;
  [0, 20, 40, 60, 80, 100].forEach((t) => {
    s += `<line class="grid" x1="${x(t)}" x2="${x(t)}" y1="${top - 8}" y2="${H - 24}"/><text x="${x(t)}" y="${H - 8}" text-anchor="middle" style="font-size:${fs}px">${t}</text>`;
  });
  s += `<circle cx="${left + 4}" cy="10" r="4.2" fill="var(--fg)"/><text x="${left + 13}" y="14" class="t-strong" style="font-size:${fs}px">staff</text>`;
  s += `<path d="M${left + 70} 5 l5 5 l-5 5 l-5 -5z" fill="var(--accent)"/><text x="${left + 80}" y="14" style="fill:var(--accent);font-size:${fs}px">management</text>`;
  data.forEach((a, i) => {
    const y = top + i * rowH + rowH / 2;
    const st = a.survey; // staff survey score
    const hot = a.blind_spot;
    const col = hot ? "var(--crit)" : "var(--line-2)";
    s += `<text x="${left - 10}" y="${y + 4}" text-anchor="end" style="font-size:${fs}px" ${hot ? 'class="t-strong"' : ""}>${esc(nm(a.name))}</text>`;
    s += `<line x1="${x(st)}" x2="${x(a.mgmt_survey)}" y1="${y}" y2="${y}" stroke="${col}" stroke-width="${hot ? 3 : 2}"/>`;
    s += `<circle cx="${x(st)}" cy="${y}" r="4.2" fill="var(--fg)"/>`;
    s += `<path d="M${x(a.mgmt_survey)} ${y - 5} l5 5 l-5 5 l-5 -5z" fill="var(--accent)"/>`;
    if (hot) s += `<text x="${x(a.mgmt_survey) + 10}" y="${y + 4}" style="fill:var(--crit);font-size:${fs}px">${sign(a.gap)}</text>`;
  });
  return s + "</svg>";
}

